"""Reproducible analysis of synthetic payment reconciliation cases; Python 3 stdlib only."""
from collections import Counter, defaultdict
from csv import DictWriter
from pathlib import Path
from random import Random

ROOT = Path(__file__).parent
RNG = Random(213)
MERCHANTS = ["Orchid Coffee", "Maple Studio", "River Books", "North Clinic", "Cedar Market"]
REASONS = ["matched", "late_settlement", "amount_mismatch", "duplicate_capture", "missing_payment", "excess_refund"]
ROWS = []
for day in range(1, 81):
    merchant = MERCHANTS[(day * 3) % len(MERCHANTS)]
    reason = RNG.choices(REASONS, weights=[56, 17, 9, 7, 8, 3])[0]
    order = RNG.randrange(10_000, 300_000, 500)
    age = RNG.randint(0, 21) if reason != "matched" else 0
    exposure = 0 if reason == "matched" else (order if reason in {"missing_payment", "duplicate_capture"} else RNG.randrange(500, min(order, 30_000) + 1, 500))
    ROWS.append({"order_id": f"SYN-{day:04d}", "merchant": merchant, "order_paise": order, "status": "matched" if reason == "matched" else "exception", "reason": reason, "age_days": age, "amount_to_investigate_paise": exposure})

with (ROOT / "synthetic_payments.csv").open("w", newline="") as stream:
    writer = DictWriter(stream, fieldnames=ROWS[0].keys())
    writer.writeheader()
    writer.writerows(ROWS)

exceptions = [row for row in ROWS if row["status"] == "exception"]
total_exposure = sum(row["amount_to_investigate_paise"] for row in exceptions)
by_reason = defaultdict(lambda: {"cases": 0, "paise": 0})
by_merchant = defaultdict(lambda: {"cases": 0, "paise": 0})
for row in exceptions:
    for bucket, key in [(by_reason, row["reason"]), (by_merchant, row["merchant"])]:
        bucket[key]["cases"] += 1
        bucket[key]["paise"] += row["amount_to_investigate_paise"]
aging = Counter("0-2" if row["age_days"] <= 2 else "3-7" if row["age_days"] <= 7 else "8+" for row in exceptions)
money = lambda paise: f"₹{paise / 100:,.2f}"
lines = [
    "# Synthetic Payment Exceptions — Analysis Report", "",
    "This report is generated from 80 deterministic, synthetic order records. Amounts to investigate are triage indicators, **not confirmed losses**.", "",
    f"- Orders: **{len(ROWS)}**",
    f"- Exceptions: **{len(exceptions)}** ({len(exceptions) / len(ROWS):.1%} of orders)",
    f"- Total amount to investigate: **{money(total_exposure)}**", "",
    "## By exception reason", "", "| Reason | Cases | Amount to investigate |", "| --- | ---: | ---: |",
]
for reason, values in sorted(by_reason.items(), key=lambda pair: pair[1]["paise"], reverse=True):
    lines.append(f"| {reason.replace('_', ' ').title()} | {values['cases']} | {money(values['paise'])} |")
lines += ["", "## By merchant", "", "| Merchant | Cases | Amount to investigate |", "| --- | ---: | ---: |"]
for merchant, values in sorted(by_merchant.items(), key=lambda pair: pair[1]["paise"], reverse=True):
    lines.append(f"| {merchant} | {values['cases']} | {money(values['paise'])} |")
lines += ["", "## Aging", "", "| Age in days | Cases |", "| --- | ---: |"]
for bucket in ["0-2", "3-7", "8+"]:
    lines.append(f"| {bucket} | {aging[bucket]} |")
top_reason = max(by_reason, key=lambda key: by_reason[key]["paise"])
lines += ["", "## Analyst recommendation", "", f"Start with **{top_reason.replace('_', ' ')}** because it has the largest amount to investigate in this sample. Review cases aged 8+ days next. Validate every amount against source transactions before escalating or reporting exposure as a loss.", "", "## Method and limits", "", "Exception rate = exception rows / all rows. Exposure = sum of row-level triage amounts. This dataset is generated by seeded random sampling and does not represent a real provider, merchant, payment volume, or measured operational performance.", ""]
(ROOT / "report.md").write_text("\n".join(lines))
print(f"Wrote {len(ROWS)} rows and report.md; exceptions={len(exceptions)}; amount_to_investigate={money(total_exposure)}")
